// Generate and verify extra exercises per stall; writes src/variants.ts.
// Usage: npx tsx scripts/gen-variants.ts [perStall=4] [seed=2026]
import { writeFileSync } from 'node:fs';
import { STALLS, authoredVariant, buildStall, NEEDS_CHANGE, NEEDS_SHARE } from '../src/levels.ts';
import { candidate, mulberry32, type Variant } from '../src/generator.ts';
import { solve } from '../src/solver.ts';
import { equationString, panTotal } from '../src/rules.ts';

const perStall = Number(process.argv[2] ?? 4);
const rng = mulberry32(Number(process.argv[3] ?? 2026));
const out: Record<string, Variant[]> = {};

for (const def of STALLS) {
  const authored = authoredVariant(def);
  // unique by equation text (same equation with different blocks would feel like a repeat)
  const eq = (v: Variant) => buildStall(def, v).scales.map(equationString).join(' | ');
  const keys = new Set([eq(authored)]);
  const list: Variant[] = [];
  let tries = 0;
  const t0 = Date.now();
  while (list.length < perStall && tries < 400) {
    tries++;
    const v = candidate(def.id, rng);
    if (!v || keys.has(eq(v))) continue;
    if (v.scales.some((s) => s.L.length > 9 || s.R.length > 9)) continue;
    if (!def.bonus) {
      const state = buildStall(def, v);
      const opts = { maxStreak: 2, maxDepth: 40, changeBox: def.changeBox, shareBoard: def.shareBoard };
      const sol = solve(state, opts);
      if (!sol || sol.moves.length < 6) continue;
      if (NEEDS_CHANGE.includes(def.id) && solve(buildStall(def, v), { ...opts, changeBox: false })) continue;
      if (NEEDS_SHARE.includes(def.id) && solve(buildStall(def, v), { ...opts, shareBoard: false })) continue;
      const blocks = [...state.scales[0].L, ...state.scales[0].R, ...state.supply].filter((i) => i.kind.startsWith('w'));
      if (panTotal(blocks, 0) < (def.seesawN ?? 0) * v.scales[0].x) continue;
      v.moves = sol.moves;
    }
    keys.add(eq(v));
    list.push(v);
    console.log(`${def.id}: +1 (${list.length}/${perStall}) after ${tries} tries, ${((Date.now() - t0) / 1000).toFixed(1)}s`);
  }
  out[def.id] = list;
}

const body = `// Generated by scripts/gen-variants.ts — verified extra exercises per stall (the authored one is added in levels.ts).
// Every entry: starts balanced only at x, has a safe solution (moves, ≤ 2 unbalanced actions in a row),
// still needs its stall's tool, fits the pans and can load the seesaw. Re-checked by tests/variants.test.ts.
import type { Variant } from './generator.ts';

export const GENERATED: Record<string, Variant[]> = ${JSON.stringify(out, null, 1)};
`;
writeFileSync('src/variants.ts', body);
console.log('wrote src/variants.ts');
